    def query_tinyllama(self, prompt, max_retries=3):
        """Query TinyLlama with retry logic"""
        for attempt in range(max_retries):
            try:
                # Generating response with enhanced settings
                response = self.generator(
                    prompt,
                    max_new_tokens=200,
                    do_sample=True,
                    temperature=0.3,
                    top_p=0.85,
                    top_k=5,
                    repetition_penalty=1.15,
                    pad_token_id=self.tokenizer.eos_token_id,
                    eos_token_id=self.tokenizer.eos_token_id
                )

                # Extracting generated text
                generated_text = response[0]['generated_text']

                
                if prompt in generated_text:
                    generated_text = generated_text.replace(prompt, "").strip()

                return generated_text

            except Exception as e:
                print(f" Attempt {attempt + 1} failed: {e}")
                if attempt < max_retries - 1:
                    time.sleep(2 ** attempt)
                else:
                    return f"ERROR: Failed after {max_retries} attempts: {str(e)}"

    def extract_prediction(self, response):
        """Enhanced prediction extraction from structured response"""
        if "ERROR:" in response:
            return 0 

        response_upper = response.upper()

       
        if "CLASSIFICATION:" in response_upper:
            # Extracting the classification line
            lines = response.split('\n')
            for line in lines:
                if 'CLASSIFICATION:' in line.upper():
                    classification_part = line.split(':', 1)[-1].strip().upper()
                    if 'FAKE' in classification_part:
                        return 1
                    elif 'REAL' in classification_part:
                        return 0

        
        if response_upper.startswith("FAKE") or "FAKE" in response_upper[:50]:
            return 1
        elif response_upper.startswith("REAL") or "REAL" in response_upper[:50]:
            return 0

        # Enhanced fallback indicators
        fake_indicators = [
            "MISINFORMATION", "FALSE", "INCORRECT", "MISLEADING", "UNTRUE",
            "NOT TRUE", "FABRICATED", "DECEPTIVE", "PROPAGANDA", "CONSPIRACY",
            "UNVERIFIED", "SUSPICIOUS", "DUBIOUS", "QUESTIONABLE"
        ]

        real_indicators = [
            "ACCURATE", "VERIFIED", "CREDIBLE", "FACTUAL", "LEGITIMATE",
            "AUTHENTIC", "RELIABLE", "TRUSTWORTHY", "VALID"
        ]

        # Counting indicators in first 100 characters for better accuracy
        response_start = response_upper[:100]
        fake_count = sum(1 for indicator in fake_indicators if indicator in response_start)
        real_count = sum(1 for indicator in real_indicators if indicator in response_start)

        if fake_count > real_count:
            return 1
        elif real_count > fake_count:
            return 0

        # Final fallback - look in full response
        if any(word in response_upper for word in fake_indicators):
            return 1
        else:
            return 0

