    def analyze_results_comparison(self, emotional_rae_file=None, baseline_file=None):
        """Compare emotional RAE vs baseline results"""
        if emotional_rae_file is None:
            model_safe = self.model_name.replace('/', '_').replace(':', '_')
            emotional_rae_file = f"results/emotional_rae_results_{model_safe}.csv"

        if baseline_file is None:
            model_safe = self.model_name.replace('/', '_').replace(':', '_')
            baseline_file = f"results/baseline_results_{model_safe}.csv"

        if not Path(emotional_rae_file).exists() or not Path(baseline_file).exists():
            print(" Results files not found. Please run inference first.")
            return

        print(" Analyzing Results Comparison...")

        # Load results
        rae_df = pd.read_csv(emotional_rae_file)
        baseline_df = pd.read_csv(baseline_file)

        #accuracies
        rae_accuracy = (rae_df['emotional_rae_prediction'] == rae_df['true_label']).mean()
        baseline_accuracy = (baseline_df['baseline_prediction'] == baseline_df['true_label']).mean()

        
        improvement = rae_accuracy - baseline_accuracy

        print(f"\n PERFORMANCE COMPARISON:")
        print(f"   Emotional RAE Accuracy: {rae_accuracy:.3f}")
        print(f"   Enhanced Baseline Accuracy: {baseline_accuracy:.3f}")
        print(f"   Improvement: {improvement:+.3f} ({improvement*100:+.1f}%)")

        # Analyze by emotion type
        if 'dominant_emotion' in rae_df.columns:
            print(f"\n ACCURACY BY EMOTION TYPE:")
            emotion_analysis = rae_df.groupby('dominant_emotion').agg({
                'emotional_rae_prediction': lambda x: (x == rae_df.loc[x.index, 'true_label']).mean(),
                'true_label': 'count'
            }).round(3)
            emotion_analysis.columns = ['accuracy', 'count']
            print(emotion_analysis)

        # Analyze by emotion intensity
        if 'emotion_intensity' in rae_df.columns:
            print(f"\n ACCURACY BY EMOTION INTENSITY:")
            rae_df['intensity_bin'] = pd.cut(rae_df['emotion_intensity'],
                                           bins=[0, 0.3, 0.6, 1.0],
                                           labels=['Low', 'Medium', 'High'])
            intensity_analysis = rae_df.groupby('intensity_bin').agg({
                'emotional_rae_prediction': lambda x: (x == rae_df.loc[x.index, 'true_label']).mean(),
                'true_label': 'count'
            }).round(3)
            intensity_analysis.columns = ['accuracy', 'count']
            print(intensity_analysis)

        return rae_df, baseline_df

