    def search_similar_emotional(self, query_text, query_emotions, top_k=5, use_emotional=True):
        """Search for similar documents using text + emotional similarity"""
        if not self.emotional_vector_store['loaded']:
            print(" Emotional vector store not loaded.")
            return None

        if len(self.emotional_vector_store['documents']) == 0:
            return None

        try:
            # Geting query text embedding
            query_text_embedding = self.embedding_model.encode([query_text])

            if use_emotional and query_emotions is not None:
                # Normalize query emotions
                query_emotions_norm = query_emotions / (np.max(query_emotions) + 1e-8)

                # Create combined query embedding
                emotion_weight = 0.2
                text_weight = 0.8
                query_combined = np.concatenate([
                    query_text_embedding * text_weight,
                    query_emotions_norm.reshape(1, -1) * emotion_weight
                ], axis=1)

                
                similarities = cosine_similarity(query_combined, self.emotional_vector_store['combined_embeddings'])[0]
            else:
                similarities = cosine_similarity(query_text_embedding, self.emotional_vector_store['text_embeddings'])[0]

            # Geting top k indices
            top_indices = np.argsort(similarities)[::-1][:top_k]

            
            results = {
                'documents': [[self.emotional_vector_store['documents'][i] for i in top_indices]],
                'metadatas': [[self.emotional_vector_store['metadata'][i] for i in top_indices]],
                'distances': [[1 - similarities[i] for i in top_indices]],
                'similarities': [[similarities[i] for i in top_indices]]
            }

            return results

        except Exception as e:
            print(f" Emotional vector search error: {e}")
            return None

