    def _add_emotional_features(self, df):
        """Add simulated emotional features to dataset"""
        np.random.seed(42)

        emotions = ['anger', 'fear', 'joy', 'sadness', 'surprise', 'neutral']

        
        for emotion in emotions:
            if emotion == 'neutral':
                # Neutral tends to be higher for real news
                df[f'emotion_{emotion}'] = np.random.beta(2, 1, len(df)) * 0.8
            else:
                # Other emotions vary based on label and text characteristics
                fake_mask = df['binary_label'] == 1

                # Adding some text-based variation
                text_lengths = df['text'].str.len()
                long_text_mask = text_lengths > text_lengths.median()

                # Real news scores (generally lower emotional intensity)
                real_scores = np.random.beta(1, 3, sum(~fake_mask)) * 0.6

                # Fake news scores (higher emotional intensity)
                fake_scores = np.random.beta(2, 1, sum(fake_mask)) * 0.9

                # Adjusting based on text length (longer texts might be more emotional)
                scores = np.zeros(len(df))
                scores[~fake_mask] = real_scores
                scores[fake_mask] = fake_scores

                # Adding slight boost for longer texts
                scores[long_text_mask] *= 1.1
                scores = np.clip(scores, 0, 1)

                df[f'emotion_{emotion}'] = scores

        # Determining dominant emotion
        emotion_cols = [f'emotion_{e}' for e in emotions]
        df['dominant_emotion'] = df[emotion_cols].idxmax(axis=1).str.replace('emotion_', '')

        # Calculating emotional intensity
        df['emotion_intensity'] = df[emotion_cols].max(axis=1)

        return df

    def create_emotional_embeddings(self, text_list, emotion_features):
        """Create combined text + emotional embeddings"""
        # Geting text embeddings
        text_embeddings = self.embedding_model.encode(text_list, show_progress_bar=True)

        # Normalize emotional features
        emotion_features_norm = emotion_features / (np.max(emotion_features, axis=0) + 1e-8)

        # Combine embeddings (text + emotional features)
        # Weight emotional features to be 20% of the embedding space
        emotion_weight = 0.2
        text_weight = 0.8

        combined_embeddings = np.concatenate([
            text_embeddings * text_weight,
            emotion_features_norm * emotion_weight
        ], axis=1)

        return text_embeddings, emotion_features_norm, combined_embeddings

